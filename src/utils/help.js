function buildHelp({ version, autoTldrThreshold = 900, commandSuffix, privateChat = null,
  voiceTranscriptionProvider = 'google' }) {
  const voiceEnabled = voiceTranscriptionProvider !== 'off';
  const voiceHelp = voiceEnabled
    ? '<li>Скажи в <b>голосовом</b> «Сыч, сколько будет два плюс два?» и получишь ответ как на текст. Голосовым реплаем на мой ответ можно продолжить разговор без имени</li>'
      + '<li>Короткий <b>войс</b> покажу свёрнутой цитатой; длинный перескажу в 2–3 предложениях. Под кнопкой «Расшифровка» доступен полный текст</li>'
    : '<li>Голосовые и аудиофайлы отключены владельцем этого бота. Напиши текстом</li>';
  const privateChatIntro = privateChat
    ? '<p><b>В личке</b> пиши текстом, можно без имени Сыча. Ниже общая справка, включая возможности в группах.</p>'
    : '';
  const privateChatFooter = privateChat
    ? '<h4>⭐ Ответы в личке</h4><p>Первые ' + privateChat.trialSize + ' ответов бесплатны.</p>'
      + '<p>Осталось бесплатных ответов: ' + privateChat.free + '.<br>Ответов из пакетов: ' + privateChat.paid + '.</p>'
      + '<p>Баланс: /balance. Купить ' + privateChat.packageSize + ' ответов за ' + privateChat.packagePrice
      + ' ⭐: /buy. Условия: /terms. Поддержка по оплате: /paysupport.</p>'
    : '';
  return `<h3>🦉 Что я умею</h3>${privateChatIntro}
<b>${voiceEnabled ? 'Вижу и слышу' : 'Сообщения и файлы'}</b>
<ul>
<li>Ответь на сообщение Сыча или на свой вопрос, на который он уже ответил, чтобы продолжить разговор. Реплай на свой вопрос действует 5 минут</li>
${voiceHelp}
<li>Длинный <b>пост в группе</b> от ${autoTldrThreshold} значимых символов автоматически перескажу реплаем: один абзац TL;DR с сутью и подсказкой, кому полезен оригинал. Ссылки и код не раздувают порог; при прямом обращении отвечаю на вопрос</li>
<li>Кидай <b>фото/видео</b> — пойму, что там, прокомментирую и запомню для вопросов потом</li>
<li>Кидай <b>PDF, DOCX, PPTX, XLSX, TXT или код</b> — прочитаю и отвечу на вопросы</li>
<li>«Сыч, перескажи [YouTube-ссылка]» — возьму субтитры, а если они закрыты — посмотрю само видео</li>
<li>Кидай ссылку на картинку — скачаю и посмотрю</li>
<li>Курс, погоду или другую конкретную цифру скажу коротко и приложу ссылку. Если попросишь проверить утверждение, разберу источники. Если нужны только ссылки, открою список сразу</li>
<li>Могу найти фото или проиллюстрировать ответ. Несколько подходящих картинок покажу в слайд-шоу</li>
<li>«Сыч напомни завтра в 10 купить молоко» — уведомлю позже. Реплаем на анонс: «Сыч напомни завтра в 12» или «Сыч напомни за час до начала»</li>
<li>«Сыч напомни, сколько дней в неделе» — отвечу сейчас. Если для уведомления не хватает времени или темы, уточню: ответь реплаем на мой вопрос.${voiceEnabled ? ' Можно голосом.' : ''} Без указанного пояса — Екатеринбург (UTC+5), можно указать МСК</li>
</ul>
<details><summary>🎲 Развлекуха</summary>
<ul>
<li>«Сыч кинь монетку» — орёл/решка</li>
<li>«Сыч число 1-100» — рандом в диапазоне</li>
<li>«Сыч кто из нас [вопрос]» — выберу случайного</li>
</ul>
</details>
<details><summary>🕵️ Досье и память</summary>
<ul>
<li>«Сыч кто я?» — моё честное мнение о тебе</li>
<li>«Сыч расскажи про @юзера» или «Сыч расскажи про TGID» — досье на участника</li>
<li>«Сыч, забудь меня» — удалить моё досье, историю и напоминания</li>
<li>«Сыч стата» — статистика токенов</li>
<li>«Сыч, этот чат про [тема]» — задать тему чата</li>
</ul>
</details>
<details><summary>⚙️ Настройки</summary>
<ul>
<li><code>/reset${commandSuffix}</code> — сброс памяти</li>
<li><code>/version${commandSuffix}</code> — версия бота</li>
</ul>
<p>${privateChat ? 'Эти команды настроек действуют в группах. Команды для лички перечислены ниже.' : 'Команды выполняются только с адресом этого бота после @, в том числе в личке. Команды другим ботам игнорируются.'}</p>
</details>
<blockquote>ver: ${version}</blockquote>${privateChatFooter}`;
}

module.exports = { buildHelp };
